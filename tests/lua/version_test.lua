local testing = require("dev.testing")
local version = require("dev.version")

testing.test("compare orders versions by major, then minor, then patch", function()
    testing.eq(version.compare("0.1.0", "0.1.0"), 0)
    testing.eq(version.compare("0.1.0", "0.2.0"), -1)
    testing.eq(version.compare("0.10.0", "0.9.9"), 1)
    testing.eq(version.compare("1.0.0", "0.99.99"), 1)
    testing.eq(version.compare("0.1.2", "0.1.10"), -1)
end)

testing.test("compare names the malformed argument", function()
    local order, reason, bad = version.compare("1.2", "0.1.0")
    testing.eq(order, nil)
    testing.eq(reason, version.Reason.MALFORMED)
    testing.eq(bad, "1.2")
    order, reason, bad = version.compare("0.1.0", "x.y.z")
    testing.eq(order, nil)
    testing.eq(reason, version.Reason.MALFORMED)
    testing.eq(bad, "x.y.z")
end)

testing.test("current reads the version beside main.lua", function()
    local current = assert(version.current())
    testing.eq(version.compare(current, current), 0)
end)
